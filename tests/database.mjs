import { PGlite } from "@electric-sql/pglite";
import { readFile, readdir } from "node:fs/promises";

export async function createTestDatabase() {
  const db = new PGlite();
  // Banco efêmero compatível com o contrato de pedidos existente; sem produtos.
  await db.exec(`
    create role anon;
    create role authenticated;
    create role service_role bypassrls;
    create schema auth;
    create table auth.users (id uuid primary key, raw_app_meta_data jsonb default '{}');
    create function auth.uid() returns uuid language sql stable as $$
      select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid;
    $$;
    insert into auth.users values ('11111111-1111-4111-8111-111111111111','{"role":"admin"}'), ('22222222-2222-4222-8222-222222222222','{}');
    create table public.orders (
      id uuid primary key default gen_random_uuid(),
      order_number bigint generated by default as identity,
      created_at timestamptz default now(), updated_at timestamptz,
      customer_name text, customer_phone text, delivery_method text,
      address text, neighborhood text, items jsonb, subtotal integer,
      delivery_fee integer, total integer, payment_method text, payment_label text,
      change_for text, notes text, status text, whatsapp_business_phone text,
      whatsapp_payload jsonb, printed_at timestamptz, print_status text,
      print_attempts integer default 0, print_error text, print_updated_at timestamptz
    );
    grant all on table public.orders to anon, authenticated, service_role;
    grant usage, select on all sequences in schema public to anon, authenticated, service_role;
  `);
  for (const filename of (await readdir("supabase/migrations")).filter((file) => file.endsWith(".sql")).sort()) {
    // PGlite já fornece gen_random_uuid, mas não empacota pgcrypto.
    const migration = (await readFile("supabase/migrations/" + filename, "utf8")).replace(/create extension if not exists pgcrypto;/gi, "");
    await db.exec(migration);
    await db.exec(migration); // idempotência de cada migration
  }
  return db;
}

export async function insertOrder(db, order) {
  const columns = Object.keys(order);
  const values = columns.map((key) => typeof order[key] === "object" && order[key] !== null
    ? JSON.stringify(order[key]) : order[key]);
  await db.exec("set role service_role");
  try {
    return (await db.query(`insert into orders (${columns.map((key) => `"${key}"`).join(",")})
      values (${values.map((_, index) => `$${index + 1}`).join(",")}) returning *`, values)).rows[0];
  } finally { await db.exec("reset role"); }
}
